"""Experiment 7: the degenerate estimator, demonstrated rather than asserted.

The specification proves that estimating each event's catalytic power from
the same state sequence that determines the measured net power makes the
two the SAME function of the data. Every discrepancy statistic then takes
its degenerate value on every data set whatsoever, so the test has no null
hypothesis and a reported agreement carries no evidential weight.

That is easy to state and easy to disbelieve, because the two quantities
are computed by routines that look independent. This script computes both
over deliberately hostile inputs -- including data generated by processes
that violate the composition law outright -- and shows the agreement is
insensitive to the generating process, which is the signature of an
identity rather than a confirmation.

It then shows the typed estimator failing, which is what a test that can
fail looks like.

Run:  python experiments/07_telescoping.py
"""

from __future__ import annotations

import math
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from vitruvius.estimation import (  # noqa: E402
    Event, composition_residual, compose_additive, compose_geometric,
    compose_maximum, compose_multiplicative, instance_specific_prediction,
    kappa, measured_net_power, telescoping_residual, type_averaged_powers,
    type_separation, typed_prediction,
)

FLOOR = 10.0
RNG = np.random.default_rng(20260817)


def cascade_multiplicative(n: int, s0: float = 100.0) -> list[Event]:
    """Data that OBEYS the composition law."""
    out, s = [], s0
    for _ in range(n):
        k = float(RNG.uniform(0.05, 0.6))
        s_next = FLOOR + (s - FLOOR) * (1.0 - k)
        out.append(Event(f"t{RNG.integers(0, 3)}", s, s_next))
        s = s_next
    return out


def cascade_adversarial(n: int, s0: float = 100.0) -> list[Event]:
    """Data generated by a process that VIOLATES every substantive claim:
    powers drawn independently of any composition rule, some negative
    (events that make the target harder to hold apart)."""
    out, s = [], s0
    for _ in range(n):
        s_next = FLOOR + max(
            (s - FLOOR) * float(RNG.uniform(0.2, 1.8)), 1e-6
        )
        out.append(Event(f"t{RNG.integers(0, 3)}", s, s_next))
        s = s_next
    return out


def cascade_random_walk(n: int, s0: float = 100.0) -> list[Event]:
    """Pure noise: no process at all."""
    out, s = [], s0
    for _ in range(n):
        s_next = FLOOR + abs(float(RNG.normal(s - FLOOR, 25.0))) + 1e-6
        out.append(Event(f"t{RNG.integers(0, 3)}", s, s_next))
        s = s_next
    return out


def part1_identity() -> None:
    print("=" * 74)
    print("PART 1  The instance-specific estimator cannot fail")
    print("=" * 74)
    print()
    print("For each generating process: the composed prediction, the directly")
    print("measured net power, and the largest absolute discrepancy over 4000")
    print("cascades. If the two were independent quantities the discrepancy")
    print("would track how well the process obeys the law.")
    print()

    generators = [
        ("multiplicative (obeys the law)", cascade_multiplicative),
        ("adversarial (violates the law)", cascade_adversarial),
        ("random walk (no process)", cascade_random_walk),
    ]

    print(f"{'generating process':<34} {'max |pred - meas|':>18} {'corr':>10}")
    print("-" * 74)

    for label, gen in generators:
        worst = 0.0
        preds, meas = [], []
        for _ in range(4000):
            c = gen(int(RNG.integers(3, 6)))
            worst = max(worst, telescoping_residual(c, FLOOR))
            p = instance_specific_prediction(c, FLOOR)
            m = measured_net_power(c, FLOOR)
            if math.isfinite(p) and math.isfinite(m):
                preds.append(p)
                meas.append(m)
        r = float(np.corrcoef(preds, meas)[0, 1]) if len(preds) > 2 else float("nan")
        print(f"{label:<34} {worst:>18.3e} {r:>10.6f}")

    print()
    print("The discrepancy is at machine precision for every process, including")
    print("processes constructed to violate the law. The agreement is therefore")
    print("not evidence about the process: it is an algebraic identity.")
    print()


def part2_typed() -> None:
    print("=" * 74)
    print("PART 2  The typed estimator can fail")
    print("=" * 74)
    print()
    print("Powers are now estimated from the event TYPE across a corpus, not")
    print("from the cascade being predicted. The two quantities are no longer")
    print("the same function of the data, so a discrepancy is possible.")
    print()

    # Well-separated types: each type has a characteristic power.
    corpus_sep: list[Event] = []
    for t, base in (("fast", 0.55), ("mid", 0.32), ("slow", 0.12)):
        for _ in range(60):
            s = float(RNG.uniform(40, 120))
            k = min(max(base + float(RNG.normal(0, 0.04)), 0.01), 0.95)
            corpus_sep.append(Event(t, s, FLOOR + (s - FLOOR) * (1 - k)))

    # Compressed types: the typing does not separate the powers.
    corpus_comp: list[Event] = []
    for t in ("fast", "mid", "slow"):
        for _ in range(60):
            s = float(RNG.uniform(40, 120))
            k = min(max(0.33 + float(RNG.normal(0, 0.22)), 0.01), 0.95)
            corpus_comp.append(Event(t, s, FLOOR + (s - FLOOR) * (1 - k)))

    for label, corpus in (("separated", corpus_sep), ("compressed", corpus_comp)):
        eta = type_separation(corpus, FLOOR)
        means = type_averaged_powers(corpus, FLOOR)

        by_type: dict[str, list[Event]] = {}
        for e in corpus:
            by_type.setdefault(e.etype, []).append(e)
        cascades = [v[i:i + 3] for v in by_type.values() for i in range(0, 45, 3)]

        resid = composition_residual(cascades, corpus, FLOOR)

        print(f"  corpus: {label}")
        print(f"    type separation  eta = {eta:.4f}")
        print(f"    type means           = "
              + ", ".join(f"{t}:{m:.3f}" for t, m in sorted(means.items())))
        print(f"    mean |pred - meas|   = {resid:.4f}   "
              f"(non-zero: the test has a null)")
        print()

    print("At high eta the typing separates and a discrepancy is interpretable.")
    print("At low eta the typing does not separate, and neither agreement nor")
    print("disagreement can be read as evidence about the composition law --")
    print("which is why eta must be reported alongside any composed estimate.")
    print()


def part3_laws() -> None:
    print("=" * 74)
    print("PART 3  Competing composition laws are ordered and distinct")
    print("=" * 74)
    print()

    bases = {"fast": 0.5, "mid": 0.3, "slow": 0.15}

    # The corpus supplies the type means.
    corpus: list[Event] = []
    for t, base in bases.items():
        for _ in range(80):
            s = float(RNG.uniform(40, 120))
            k = min(max(base + float(RNG.normal(0, 0.05)), 0.01), 0.95)
            corpus.append(Event(t, s, FLOOR + (s - FLOOR) * (1 - k)))

    means = type_averaged_powers(corpus, FLOOR)

    # Cascades must MIX types, or every cascade has near-identical powers
    # and the four laws produce near-identical predictions -- the test
    # would then be comparing constants and could not select among them.
    cascades: list[list[Event]] = []
    for _ in range(400):
        s = float(RNG.uniform(60, 140))
        chain: list[Event] = []
        for _ in range(int(RNG.integers(3, 6))):
            t = str(RNG.choice(list(bases)))
            k = min(max(bases[t] + float(RNG.normal(0, 0.05)), 0.01), 0.95)
            s_next = FLOOR + (s - FLOOR) * (1 - k)
            chain.append(Event(t, s, s_next))
            s = s_next
        cascades.append(chain)

    laws = {
        "multiplicative": compose_multiplicative,
        "additive": compose_additive,
        "geometric mean": compose_geometric,
        "maximum": compose_maximum,
    }

    print(f"{'law':<18} {'RMSE':>10} {'corr':>10}")
    print("-" * 42)

    for name, fn in laws.items():
        preds, meas = [], []
        for c in cascades:
            ks = [means.get(e.etype, 0.0) for e in c]
            p = fn(ks)
            m = measured_net_power(c, FLOOR)
            if math.isfinite(p) and math.isfinite(m):
                preds.append(p)
                meas.append(m)
        if len(preds) < 3:
            continue
        rmse = float(np.sqrt(np.mean((np.array(preds) - np.array(meas)) ** 2)))
        r = float(np.corrcoef(preds, meas)[0, 1])
        print(f"{name:<18} {rmse:>10.4f} {r:>10.4f}")

    print()
    print("The data were generated multiplicatively, so the multiplicative law")
    print("should win -- and because the four laws are ordered and distinct,")
    print("that outcome is a genuine selection rather than a foregone one.")
    print()


def collect() -> dict:
    """Same computations, returned as data for JSON export."""
    out = {"parts": {}}

    # Part 1: the identity holds regardless of generating process.
    gens = {
        "multiplicative_obeys_law": cascade_multiplicative,
        "adversarial_violates_law": cascade_adversarial,
        "random_walk_no_process": cascade_random_walk,
    }
    p1 = {}
    for label, gen in gens.items():
        worst, preds, meas = 0.0, [], []
        for _ in range(4000):
            c = gen(int(RNG.integers(3, 6)))
            worst = max(worst, telescoping_residual(c, FLOOR))
            a, b = (instance_specific_prediction(c, FLOOR),
                    measured_net_power(c, FLOOR))
            if math.isfinite(a) and math.isfinite(b):
                preds.append(a); meas.append(b)
        p1[label] = {
            "max_abs_discrepancy": worst,
            "pearson_r": float(np.corrcoef(preds, meas)[0, 1]),
            "n_cascades": 4000,
        }
    out["parts"]["instance_specific_identity"] = {
        "claim": "the instance-specific estimator agrees with its own "
                 "measurement on every data set, so the test has no null",
        "by_generating_process": p1,
    }

    # Part 2: the typed estimator can fail; eta says when it is readable.
    p2 = {}
    for label, spread, bases in (
        ("separated", 0.04, {"fast": 0.55, "mid": 0.32, "slow": 0.12}),
        ("compressed", 0.22, {"fast": 0.33, "mid": 0.33, "slow": 0.33}),
    ):
        corpus = []
        for t, base in bases.items():
            for _ in range(60):
                s_b = float(RNG.uniform(40, 120))
                k = min(max(base + float(RNG.normal(0, spread)), 0.01), 0.95)
                corpus.append(Event(t, s_b, FLOOR + (s_b - FLOOR) * (1 - k)))
        by_type = {}
        for e in corpus:
            by_type.setdefault(e.etype, []).append(e)
        cascades = [v[i:i + 3] for v in by_type.values() for i in range(0, 45, 3)]
        p2[label] = {
            "type_separation_eta": type_separation(corpus, FLOOR),
            "type_means": type_averaged_powers(corpus, FLOOR),
            "mean_abs_discrepancy": composition_residual(cascades, corpus, FLOOR),
            "n_corpus": len(corpus),
        }
    out["parts"]["typed_estimator"] = {
        "claim": "estimating from the event type breaks the identity, so a "
                 "discrepancy is possible and the test has a null",
        "by_corpus": p2,
    }

    # Part 3: the four laws are distinct and orderable.
    bases = {"fast": 0.5, "mid": 0.3, "slow": 0.15}
    corpus = []
    for t, base in bases.items():
        for _ in range(80):
            s_b = float(RNG.uniform(40, 120))
            k = min(max(base + float(RNG.normal(0, 0.05)), 0.01), 0.95)
            corpus.append(Event(t, s_b, FLOOR + (s_b - FLOOR) * (1 - k)))
    means = type_averaged_powers(corpus, FLOOR)
    cascades = []
    for _ in range(400):
        s_b = float(RNG.uniform(60, 140))
        chain = []
        for _ in range(int(RNG.integers(3, 6))):
            t = str(RNG.choice(list(bases)))
            k = min(max(bases[t] + float(RNG.normal(0, 0.05)), 0.01), 0.95)
            nxt = FLOOR + (s_b - FLOOR) * (1 - k)
            chain.append(Event(t, s_b, nxt)); s_b = nxt
        cascades.append(chain)

    laws = {"multiplicative": compose_multiplicative,
            "additive": compose_additive,
            "geometric_mean": compose_geometric,
            "maximum": compose_maximum}
    p3 = {}
    for nm, fn in laws.items():
        preds, meas = [], []
        for c in cascades:
            a = fn([means.get(e.etype, 0.0) for e in c])
            b = measured_net_power(c, FLOOR)
            if math.isfinite(a) and math.isfinite(b):
                preds.append(a); meas.append(b)
        p3[nm] = {
            "rmse": float(np.sqrt(np.mean((np.array(preds) - np.array(meas)) ** 2))),
            "pearson_r": float(np.corrcoef(preds, meas)[0, 1]),
        }
    out["parts"]["law_comparison"] = {
        "claim": "the four composition laws are distinct and ordered, so a "
                 "corpus with adequate eta can select among them",
        "generating_process": "multiplicative",
        "laws": p3,
        "n_cascades": len(cascades),
    }
    return out


if __name__ == "__main__":
    import json

    part1_identity()
    part2_typed()
    part3_laws()

    data = collect()
    out = Path(__file__).resolve().parent.parent / "results" / "07_telescoping.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(data, indent=2), encoding="utf-8")
    print(f"wrote {out}")
